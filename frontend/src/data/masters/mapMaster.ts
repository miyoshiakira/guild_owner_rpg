// ── 型定義 ────────────────────────────────────────────────────────────────
export interface MapTransition {
  /** このマップ上のポータル位置 */
  fromRow: number;
  fromCol: number;
  /** 遷移先マップ ID */
  toMapId: string;
  /** 遷移先での出現位置（ポータルの隣） */
  toRow: number;
  toCol: number;
  /** 遷移先の表示名 */
  label: string;
}

export interface MapMasterData {
  id: string;
  name: string;
  description: string;
  emoji: string;
  /** 敵がスポーンするタイル種別 */
  enemySpawnTiles: number[];
  /** マップ遷移ポイント一覧 */
  transitions: MapTransition[];
  /** このマップに初めて来たときのデフォルト位置 */
  defaultPos: { row: number; col: number };
  /** 20×20 タイルグリッド */
  tileMap: number[][];
}

